import { expect, it } from "vitest";
import {
  projectLabel,
  promptLabel,
  sessionRow,
  sessionTitle,
  sessionSubtitle,
  shortProject,
} from "./data";

it("preserves only the explicit recorded top-level list agent metadata", () => {
  const base = { sessionId: "s", source: "codex" };
  expect(sessionRow({ ...base, agentName: "  yo-2  " }).agentName).toBe("yo-2");
  expect(sessionRow({ ...base, catalog: { agentName: "old-detail" }, agentName: "yo-2" }).agentName).toBe("yo-2");
  for (const agentName of [undefined, null, "", "  ", 1, ["yo-1"], { name: "yo-1" }]) {
    expect(sessionRow({ ...base, catalog: { agentName }, agentName }).agentName).toBeNull();
  }
  expect(sessionRow({ ...base, title: "yo-1", actor: "yo-1", catalog: { agentName: "detail-only" }, agent_names: ["yo-1"], agent_name: "yo-1" }).agentName).toBeNull();
});

it.each([
  [{ agentName: "yo-1", models: ["gpt-6.1-sol"] }, "Codex · yo-1 · gpt-6.1-sol"],
  [{ models: ["gpt-6.1-sol"] }, "Codex · gpt-6.1-sol"],
  [{ agentName: "yo-1" }, "Codex · yo-1"],
  [{}, "Codex"],
  [{ agentName: " CODEX ", models: ["codex"] }, "Codex"],
  [{ agentName: " gpt-6.1-sol ", models: [" GPT-6.1-SOL "] }, "Codex · gpt-6.1-sol"],
  [{ agentName: " \t yo-1\n ", models: [" ", "\t gpt-6.1-sol  ", "second-model"] }, "Codex · yo-1 · gpt-6.1-sol"],
])("renders recorded execution metadata %# without blank or duplicate parts", (metadata, expected) => {
  expect(sessionSubtitle(sessionRow({ sessionId: "s", source: "codex", ...metadata }))).toBe(expected);
});

it("preserves only recorded short summaries without using prompt text as a substitute", () => {
  const base = { sessionId: "s", source: "codex", summary: "A prompt, not a generated summary" };
  expect(sessionRow({ ...base, shortSummary: "  Fixed the loader.  " }).shortSummary).toBe("Fixed the loader.");
  for (const shortSummary of [undefined, null, "", "  ", { text: "invalid" }]) {
    expect(sessionRow({ ...base, shortSummary }).shortSummary).toBeNull();
  }
});

it("titles skip injected wrappers and use the first real sentence", () => {
  expect(
    promptLabel(
      "<system-reminder>\nAgent Relay MCP tools are available in this session.\n</system-reminder>\nFix the flaky login test",
    ),
  ).toBe("Fix the flaky login test");
  expect(
    promptLabel(
      "<environment_context>\n<cwd>/Users/k/repo</cwd>\n</environment_context>\n<user_instructions>use npm</user_instructions>\nShip the sessions page",
    ),
  ).toBe("Ship the sessions page");
  expect(
    promptLabel(
      "# AGENTS.md instructions for /Users/k/repo\n\n<INSTRUCTIONS>\nBe careful.\n</INSTRUCTIONS>\n\nAdd retries to the uploader",
    ),
  ).toBe("Add retries to the uploader");
  expect(
    promptLabel(
      "Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.",
    ),
  ).toBeNull();
  // As hosted: a slash command's wrapper is replaced by the command itself.
  expect(
    promptLabel(
      "<command-name>/review</command-name>\n<command-message>review</command-message>\n<command-args>PR 80</command-args>",
    ),
  ).toBe("/review PR 80");
  expect(promptLabel("<pasted_content>stack trace here</pasted_content>")).toBe(
    "stack trace here",
  );
  expect(promptLabel("x".repeat(200))).toHaveLength(88);
  expect(
    promptLabel(
      "<system-reminder>\nAgent Relay MCP tools are available for replies.\n</system-reminder>\nRelay message from broker [init_7d87]: Repo: AgentWorkforce/software-garden. Khaliq wants this to stop now. The repo is being deprecated and its scheduled review workflow keeps failing every ten minutes, so disable it and any other cron workflows.",
      160,
    ),
  ).toBe("Khaliq wants this to stop now.");
  // A summary cut off inside an injected block has no typed text left.
  expect(
    promptLabel(
      "<system-reminder> Agent Relay MCP tools are available for replies. - For…",
    ),
  ).toBeNull();
});

it("falls back from title to task title to summary to the project and id", () => {
  const row = sessionRow({
    sessionId: "01a14c35-6e57",
    source: "codex",
    summary: "<system-reminder>tools</system-reminder>",
    projectId:
      "/Users/k/Projects/AgentWorkforce/relay-desktop/.relayflow/context-review/user-facing",
  });
  expect(sessionTitle(row)).toBe("AgentWorkforce/relay-desktop · 01a14c35");
  expect(sessionTitle({ ...row, taskTitle: "Review the change" })).toBe(
    "Review the change",
  );
  expect(
    sessionTitle({ ...row, title: "Catalog title", taskTitle: "Task" }),
  ).toBe("Catalog title");
  expect(sessionTitle({ ...row, summary: "Fix the flaky loader" })).toBe(
    "Fix the flaky loader",
  );
});

it("shortens project paths and remotes, keeping the full value for tooltips", () => {
  expect(
    shortProject(
      "/Users/k/Projects/AgentWorkforce/relay-desktop/.relayflow/context-review/user-facing",
    ),
  ).toBe("AgentWorkforce/relay-desktop");
  expect(shortProject("/Users/k/code/cloud/.claude/worktrees/fix-login")).toBe(
    "k/code/cloud".split("/").slice(-2).join("/"),
  );
  expect(
    shortProject("https://github.com/AgentWorkforce/relay-desktop.git"),
  ).toBe("AgentWorkforce/relay-desktop");
  expect(shortProject("git@github.com:AgentWorkforce/relay.git")).toBe(
    "AgentWorkforce/relay",
  );
  expect(shortProject("github.com/AgentWorkforce/cloud")).toBe(
    "AgentWorkforce/cloud",
  );
  expect(shortProject("relay")).toBe("relay");
  const row = sessionRow({
    sessionId: "s",
    source: "claude",
    projectId: "/very/long/path/AgentWorkforce/relay",
    catalog: { repoUrl: "https://github.com/AgentWorkforce/relay" },
  });
  expect(projectLabel(row)).toEqual({
    name: "AgentWorkforce/relay",
    detail: "https://github.com/AgentWorkforce/relay",
  });
});

